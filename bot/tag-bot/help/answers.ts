export type HelpIntent = keyof typeof fixedAnswers | 'page-timing';
export const helpIntents: HelpIntent[] = [...Object.keys(fixedAnswers) as (keyof typeof fixedAnswers)[], 'page-timing'];

export function describeConfiguredTiming(
  rows: PageToArchive[],
  page: string,
  requestedStatus: string,
): string {
  const applicable = rows.filter((entry) => entry.page === page && entry.statuses.includes(requestedStatus));
  const [rule] = applicable;
  if (!rule || applicable.length !== 1) {
    return `כדי לזהות את זמן ההמתנה, צריך את הדף המדויק ואת הערך שמופיע בתבנית ${template('מצב')}. ${statusDocs}`;
  }
  const target = rule.archiveType === 'תבנית ארכיון עם יעד'
    ? ` בהגדרה הזו נדרש גם ערך בפרמטר ״ארכוב״ בתבנית ${template('מצב')}; בלי ערך הדיון נשאר בדף.`
    : '';
  return `למצב הזה הוגדרו ${rule.daysAfterLastActivity} ימי המתנה מהחתימה האחרונה שזוהתה. אם אין חתימה מזוהה, הספירה מתחילה מהרישום הראשון בדף המעקב.${target} כדי לבדוק דיון מסוים צריך קישור לפסקה. ${statusDocs}`;
}
